
# ============================================================
# 실습 주제 : 상품 주문 금액 및 할인 적용 결제액 계산
#
# 학습 목표
# 1. input() 함수를 이용하여 사용자로부터 데이터를 입력받습니다.
# 2. 변수에 입력값을 저장하는 방법을 학습합니다.
# 3. str, int, float 자료형의 차이를 이해합니다.
# 4. int(), float()를 이용한 자료형 변환을 학습합니다.
# 5. 산술 연산자를 이용하여 상품 금액과 할인 금액을 계산합니다.
# 6. f-string을 이용하여 결과를 보기 좋게 출력합니다.
# ============================================================


# ------------------------------------------------------------
# 1단계 : 상품명 입력받기
# ------------------------------------------------------------

# input() 함수는 키보드로 입력한 값을 받아오는 함수입니다.
# 괄호 안의 "상품명: "은 사용자에게 보여줄 안내 문구입니다.
# 사용자가 입력한 값은 product_name 변수에 저장됩니다.
# input() 함수로 입력받은 값의 자료형은 항상 str(문자열)입니다.
#
# 예) 사용자가 "노트북"을 입력하면
#     product_name = "노트북" 이 됩니다.

product_name = input("상품명: ")


# ------------------------------------------------------------
# 2단계 : 상품 단가 입력받기
# ------------------------------------------------------------

# 상품의 가격(단가)을 입력받습니다.
# 사용자가 10000을 입력하더라도 input()은 문자열로 저장합니다.
#
# 예) 10000 입력
#     price_text = "10000"
#
# 주의!
# "10000"은 문자열(str)이고 10000은 정수(int)입니다.
# 둘은 자료형이 다릅니다.

price_text = input("단가(숫자만): ")


# ------------------------------------------------------------
# 3단계 : 입력받은 데이터의 자료형 확인
# ------------------------------------------------------------

# type() 함수는 데이터의 자료형을 확인하는 함수입니다.
# price_text는 input()으로 입력받았기 때문에 str 자료형입니다.
#
# 출력 예) 입력 자료형: <class 'str'>
#
# <class 'str'>은 문자열 자료형이라는 의미입니다.

print("입력 자료형:", type(price_text))


# ------------------------------------------------------------
# 4단계 : 문자열을 정수로 변환하기
# ------------------------------------------------------------

# int() 함수는 정수 형태의 문자열을 정수로 변환합니다.
#
# 변환 전 : price_text = "10000" → str(문자열)
# 변환 후 : price = 10000        → int(정수)
#
# 가격 계산을 위해 문자열을 숫자로 변환하는 과정입니다.
#
# 주의!
# "만원", "10,000", "1000원" 등을 입력하면
# int()로 바로 변환할 수 없어 ValueError가 발생합니다.
# 따라서 숫자만 입력해야 합니다.

price = int(price_text)


# ------------------------------------------------------------
# 5단계 : 상품 수량 입력받기
# ------------------------------------------------------------

# 상품의 구매 수량을 입력받습니다.
#
# input()으로 입력받은 값은 문자열이므로
# int()를 이용해 정수로 변환합니다.
#
# 예) 사용자가 3을 입력하면
#     input() 결과는 "3" (문자열)
#     int("3") 결과는 3 (정수)
#
# int(input())은 입력과 정수 변환을 한 줄로 처리한 것입니다.

quantity = int(input("수량(정수): "))


# ------------------------------------------------------------
# 6단계 : 할인율 입력받기
# ------------------------------------------------------------

# 사용자에게 할인율을 백분율(%)로 입력받습니다.
#
# float() 함수는 문자열을 실수(float)로 변환합니다.
# 실수는 소수점을 포함할 수 있는 숫자입니다.
#
# 예) 10 입력   → 10.0
#     12.5 입력 → 12.5
#
# 할인율은 소수점이 있을 수 있으므로 float()를 사용합니다.
#
# 주의!
# 할인율 입력 시 % 기호는 입력하지 않습니다.
# 예) 10% 할인이라면 10만 입력합니다.

discount_rate = float(input("할인율(%): "))


# ------------------------------------------------------------
# 7단계 : 할인 전 상품 총금액 계산
# ------------------------------------------------------------

# 단가(price)에 구매 수량(quantity)을 곱합니다.
#
# * 는 Python의 곱셈 연산자입니다.
#
# 계산 공식
# 할인 전 금액 = 상품 단가 × 구매 수량
#
# 예) 단가 10000원, 수량 3개
#     subtotal = 10000 * 3
#     subtotal = 30000

subtotal = price * quantity


# ------------------------------------------------------------
# 8단계 : 할인 적용 후 최종 결제액 계산
# ------------------------------------------------------------

# 할인율을 적용하여 실제 결제할 금액을 계산합니다.
#
# 계산 공식
# 최종 결제액 = 할인 전 금액 × (1 - 할인율 / 100)
#
# 예) 할인 전 금액 : 30000원
#     할인율       : 10%
#
# ① discount_rate / 100
#    10 / 100 = 0.1
#    → 10%를 소수 0.1로 변환
#
# ② 1 - 0.1
#    = 0.9
#    → 원래 금액의 90%를 결제한다는 의미
#
# ③ subtotal * 0.9
#    = 30000 * 0.9
#    = 27000.0
#
# 따라서 최종 결제액은 27000원입니다.
#
# 참고!
# / 연산자의 결과는 일반적으로 float 자료형입니다.

total = subtotal * (1 - discount_rate / 100)


# ------------------------------------------------------------
# 9단계 : 최종 결제 결과 출력
# ------------------------------------------------------------

# print() 함수는 화면에 결과를 출력하는 함수입니다.
#
# f-string은 문자열 앞에 f를 붙여
# 문자열 안에 변수의 값을 삽입하는 방법입니다.
#
# {product_name} → 상품명 출력
# {quantity}     → 구매 수량 출력
#
# {total:,.0f}의 의미
#   :  → 출력 형식을 지정하는 기호
#   ,  → 천 단위마다 쉼표(,) 표시
#   .0f → 소수점 이하 0자리까지 표시(반올림)
#
# 예) total = 27000.0
#     일반 출력      → 27000.0
#     {total:,.0f}  → 27,000
#
# 주의!
# .0f는 출력할 때 반올림하여 표시하는 형식이며,
# total 변수에 저장된 실제 값을 변경하지 않습니다.

print(f"{product_name} {quantity}개 / 결제액 {total:,.0f}원")
